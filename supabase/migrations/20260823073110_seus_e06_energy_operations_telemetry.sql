create table if not exists energy.outage_events (
  outage_id uuid primary key default gen_random_uuid(),
  project_id uuid references energy.projects(project_id) on delete set null,
  asset_id uuid references energy.assets(asset_id) on delete set null,
  source_id uuid references energy.measurement_sources(source_id) on delete set null,
  outage_type text not null check (outage_type in ('PLANNED','FORCED','DERATE','GRID_CURTAILMENT','FUEL_CONSTRAINT','MAINTENANCE','COMMUNICATIONS','OTHER')),
  outage_state text not null default 'REPORTED' check (outage_state in ('REPORTED','PENDING_VERIFICATION','VERIFIED','ACTIVE','RESTORED','CLOSED','DISPUTED','REJECTED','ARCHIVED')),
  started_at timestamptz not null,
  ended_at timestamptz,
  unavailable_capacity_mw numeric check (unavailable_capacity_mw is null or unavailable_capacity_mw >= 0),
  cause_reference text,
  evidence_reference text,
  external_reference text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (project_id is not null or asset_id is not null),
  check (ended_at is null or ended_at > started_at)
);

