create table if not exists energy.measurement_sources (
  source_id uuid primary key default gen_random_uuid(),
  source_code text not null unique check (source_code ~ '^[A-Z0-9_-]{3,64}$'),
  source_type text not null check (source_type in ('UTILITY_METER','SCADA','BMS','EMS','INVERTER','BATTERY_MGMT','MANUAL_ATTESTATION','API','FILE_IMPORT','MODEL','FORECAST','OTHER')),
  source_name text not null check (length(btrim(source_name)) > 0),
  authority_state text not null default 'REFERENCE' check (authority_state in ('REFERENCE','PENDING_VERIFICATION','VERIFIED_SOURCE','AUTHORITATIVE_SOURCE','DISPUTED','ARCHIVED')),
  external_reference text,
  evidence_reference text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
comment on table energy.measurement_sources is 'Registry of operational measurement and modeling sources. MODEL and FORECAST sources are non-observed by definition and must not be treated as verified physical telemetry.';

create table if not exists energy.meters (
  meter_id uuid primary key default gen_random_uuid(),
  meter_code text not null unique check (meter_code ~ '^[A-Z0-9_-]{3,64}$'),
  source_id uuid references energy.measurement_sources(source_id) on delete set null,
  project_id uuid references energy.projects(project_id) on delete set null,
  asset_id uuid references energy.assets(asset_id) on delete set null,
  meter_type text not null check (meter_type in ('REVENUE','GENERATION','LOAD','NET','SUBMETER','STORAGE_CHARGE','STORAGE_DISCHARGE','FUEL','THERMAL','OTHER')),
  unit text not null,
  multiplier numeric not null default 1 check (multiplier > 0),
  meter_state text not null default 'REFERENCE' check (meter_state in ('REFERENCE','PENDING_VERIFICATION','VERIFIED','ACTIVE','INACTIVE','DISPUTED','RETIRED','ARCHIVED')),
  external_reference text,
  evidence_reference text,
  commissioned_at timestamptz,
  retired_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (project_id is not null or asset_id is not null)
);

create table if not exists energy.meter_readings (
  reading_id bigint generated by default as identity primary key,
  meter_id uuid not null references energy.meters(meter_id) on delete restrict,
  source_id uuid references energy.measurement_sources(source_id) on delete set null,
  reading_kind text not null check (reading_kind in ('OBSERVED','ESTIMATED','MODELED','FORECAST','CORRECTED')),
  interval_start timestamptz not null,
  interval_end timestamptz not null,
  quantity numeric not null,
  unit text not null,
  quality_state text not null default 'UNVERIFIED' check (quality_state in ('UNVERIFIED','SOURCE_VERIFIED','VALIDATED','ESTIMATED','MODELED','FORECAST','CORRECTED','DISPUTED','REJECTED')),
  external_reference text,
  evidence_reference text,
  correction_of_reading_id bigint references energy.meter_readings(reading_id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  observed_at timestamptz,
  created_at timestamptz not null default now(),
  check (interval_end > interval_start),
  check ((reading_kind = 'MODELED' and quality_state in ('MODELED','UNVERIFIED')) or
         (reading_kind = 'FORECAST' and quality_state in ('FORECAST','UNVERIFIED')) or
         (reading_kind not in ('MODELED','FORECAST')))
);
comment on table energy.meter_readings is 'Time-bounded meter readings with explicit observed/estimated/modeled/forecast classification. MODELED or FORECAST records cannot carry VALIDATED or SOURCE_VERIFIED quality.';

create table if not exists energy.generation_observations (
  observation_id bigint generated by default as identity primary key,
  project_id uuid references energy.projects(project_id) on delete set null,
  asset_id uuid references energy.assets(asset_id) on delete set null,
