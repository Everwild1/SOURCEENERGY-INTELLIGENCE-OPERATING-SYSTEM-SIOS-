-- Public-safe Capitalization Block API projection and security boundary.
-- Only registry metadata and non-financial system metrics are published.
-- No balances, commitments, account references, evidence documents, settlement
-- instructions, credentials, or secrets are exposed here.

BEGIN;

REVOKE ALL ON SCHEMA capitalization_api FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA capitalization_api TO anon, authenticated, service_role;

ALTER DEFAULT PRIVILEGES IN SCHEMA capitalization_api
    REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA capitalization_api
    REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA capitalization_api
    REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS capitalization_api.network_directory (
    directory_entry_id text PRIMARY KEY,
    institution_reference text NOT NULL,
    institution_display_name text NOT NULL,
    institution_type text NOT NULL,
    jurisdiction_code text,
    region_code text,
    sourceenergy_node_id text NOT NULL,
    dominion_cube_id text,
    relay_code text,
    layer_number integer,
    operational_role text,
    relationship_state text NOT NULL,
    connectivity_status text NOT NULL,
    verification_status text NOT NULL,
    public_claim_status text NOT NULL,
    relationship_label text NOT NULL,
    connectivity_label text NOT NULL,
    last_verified_at timestamptz,
    disclosure text NOT NULL,
    is_published boolean NOT NULL DEFAULT true,
    published_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT capitalization_api_network_directory_claim_chk CHECK (
        public_claim_status IN (
            'REGISTRY_TARGET', 'EVIDENCE_BACKED_NON_LIVE', 'VERIFIED_LIVE'
        )
    ),
    CONSTRAINT capitalization_api_network_directory_live_chk CHECK (
        public_claim_status <> 'VERIFIED_LIVE'
        OR (
            relationship_state = 'LIVE'
            AND connectivity_status = 'PRODUCTION'
            AND verification_status = 'VERIFIED'
            AND last_verified_at IS NOT NULL
        )
    )
);

CREATE TABLE IF NOT EXISTS capitalization_api.dashboard_metrics (
    metric_code text PRIMARY KEY,
    metric_name text NOT NULL,
    numeric_value numeric(38, 12),
    text_value text,
    unit text,
    measurement_kind text NOT NULL DEFAULT 'SYSTEM_DERIVED',
    as_of timestamptz NOT NULL,
    disclosure text NOT NULL,
    is_published boolean NOT NULL DEFAULT true,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT capitalization_api_dashboard_metrics_value_chk CHECK (
        numeric_value IS NOT NULL OR text_value IS NOT NULL
    ),
    CONSTRAINT capitalization_api_dashboard_metrics_kind_chk CHECK (
        measurement_kind IN ('SYSTEM_DERIVED', 'OBSERVED', 'VERIFIED')
    )
);

CREATE TABLE IF NOT EXISTS capitalization_api.api_contract_versions (
    contract_name text NOT NULL,
    contract_version text NOT NULL,
    status text NOT NULL DEFAULT 'ACTIVE',
    documentation_reference text NOT NULL,
    authority_boundary text NOT NULL,
    effective_at timestamptz NOT NULL DEFAULT now(),
    retired_at timestamptz,
    PRIMARY KEY (contract_name, contract_version),
    CONSTRAINT capitalization_api_contract_status_chk CHECK (
        status IN ('DRAFT', 'ACTIVE', 'DEPRECATED', 'RETIRED')
    ),
    CONSTRAINT capitalization_api_contract_retired_chk CHECK (
        status <> 'RETIRED' OR retired_at IS NOT NULL
    )
);

INSERT INTO capitalization_api.api_contract_versions (
    contract_name,
    contract_version,
    status,
    documentation_reference,
    authority_boundary
) VALUES (
