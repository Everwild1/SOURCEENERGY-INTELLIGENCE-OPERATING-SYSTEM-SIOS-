ON capitalization_api.api_contract_versions
FOR SELECT
TO anon, authenticated
USING (status IN ('ACTIVE', 'DEPRECATED'));

REVOKE ALL ON ALL TABLES IN SCHEMA capitalization_api FROM PUBLIC, anon, authenticated;
GRANT SELECT ON capitalization_api.network_directory TO anon, authenticated;
GRANT SELECT ON capitalization_api.dashboard_metrics TO anon, authenticated;
GRANT SELECT ON capitalization_api.api_contract_versions TO anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA capitalization_api TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA capitalization_api TO service_role;

REVOKE ALL ON capitalization.public_projection_refresh_history FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON capitalization.public_projection_refresh_history TO service_role;

REVOKE EXECUTE ON FUNCTION capitalization.refresh_public_network_projection(text)
    FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION capitalization.refresh_public_network_projection(text)
    TO service_role;

COMMENT ON TABLE capitalization_api.network_directory IS
'Public-safe SourceEnergy institutional registry projection. Registry-target rows are not participating-bank claims. Financial and evidentiary data are excluded.';
COMMENT ON TABLE capitalization_api.dashboard_metrics IS
'Non-financial public system metrics only. Treasury balances, commitments, settlement amounts, and exposures are prohibited from this table.';
COMMENT ON FUNCTION capitalization.refresh_public_network_projection(text) IS
'Server-only projection refresh. A VERIFIED_LIVE label requires the public claim gate plus verified relationship, institution, and production node evidence.';

COMMIT;
